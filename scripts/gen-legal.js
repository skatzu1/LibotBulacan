/*
 * Writes utils/legalText.js — the Terms and Conditions and Privacy Policy the
 * sign-up consent pop-up shows (components/LegalConsentModal.js) — from the
 * website's own pages, so the app never shows different words from
 * libotbulacan.com/terms and /privacy.
 *
 *   node scripts/gen-legal.js [path/to/libot-download-site]
 *
 * Default source: ../LibotWeb/libot-download-site. Run it whenever either page
 * changes, then ship the app (an OTA update is enough). LEGAL_VERSION is the
 * later of the two effective dates; it is what the backend records as the
 * version a traveler agreed to.
 */
const fs = require("fs");
const path = require("path");

const siteDir = path.resolve(process.argv[2] || path.join(__dirname, "..", "..", "LibotWeb", "libot-download-site"));
const outFile = path.join(__dirname, "..", "utils", "legalText.js");

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", copy: "©", ndash: "–", mdash: "—", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", hellip: "…" };
const decode = (s) => s
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
  .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
  .replace(/&([a-z]+);/gi, (m, name) => ENTITIES[name.toLowerCase()] ?? m);

const MONTHS = ["january", "february", "march", "april", "may", "june", "july", "august", "september", "october", "november", "december"];
/** "20 October 2026" → "2026-10-20". */
function isoDate(text) {
  const m = /(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})/.exec(text || "");
  const month = m ? MONTHS.indexOf(m[2].toLowerCase()) : -1;
  if (month < 0) throw new Error(`Can't read the effective date "${text}"`);
  return `${m[3]}-${String(month + 1).padStart(2, "0")}-${m[1].padStart(2, "0")}`;
}

/**
 * The page's title, effective date and body as blocks:
 *   { type: "h", text } · { type: "p", runs, lede? } · { type: "li", runs, depth }
 * where runs = [{ text, bold? }]. Links keep their words; the rest of the
 * markup (sections, emphasis, line breaks) is flattened.
 */
function parsePage(file) {
  const html = fs.readFileSync(file, "utf8");
  const title = decode((/<h1[^>]*>([\s\S]*?)<\/h1>/.exec(html) || [])[1] || "").trim();
  const effective = decode((/<p class="doc-meta">([\s\S]*?)<\/p>/.exec(html) || [])[1] || "").replace(/^Effective\s+/i, "").trim();
  const start = html.indexOf('<div class="doc-body">');
  const end = html.indexOf("</article>", start);
  if (start < 0 || end < 0) throw new Error(`No doc-body in ${file}`);
  const body = html.slice(start + '<div class="doc-body">'.length, end);

  const blocks = [];
  let block = null;
  let depth = 0;
  let bold = 0;
  const flush = () => {
    if (block) {
      block.runs = block.runs
        .map((r) => ({ ...r, text: r.text.replace(/\s+/g, " ") }))
        .filter((r) => r.text);
      if (block.runs.length) {
        block.runs[0].text = block.runs[0].text.replace(/^\s+/, "");
        const last = block.runs[block.runs.length - 1];
        last.text = last.text.replace(/\s+$/, "");
        if (block.type === "h") blocks.push({ type: "h", text: block.runs.map((r) => r.text).join("") });
        else blocks.push(block);
      }
    }
    block = null;
  };
  const open = (type, extra = {}) => { flush(); block = { type, runs: [], ...extra }; };

  for (const m of body.matchAll(/<(\/?)([a-z0-9]+)([^>]*)>|([^<]+)/gi)) {
    const [, closing, rawTag, attrs, text] = m;
    if (text !== undefined) {
      if (!block) { if (!text.trim()) continue; open("p"); }
      block.runs.push({ text: decode(text), ...(bold > 0 && { bold: true }) });
      continue;
    }
    const tag = rawTag.toLowerCase();
    if (["h2", "h3", "p", "li"].includes(tag) && closing) flush();
    else if (tag === "h2" || tag === "h3") open("h");
    else if (tag === "p") open("p", /class="lede"/.test(attrs) ? { lede: true } : {});
    else if (tag === "li") open("li", { depth: Math.max(1, depth) });
    else if (tag === "ul" || tag === "ol") {
      if (closing) depth -= 1;
      else { flush(); depth += 1; }
    } else if (tag === "strong" || tag === "b") bold += closing ? -1 : 1;
    else if (tag === "br" && block) block.runs.push({ text: " " });
    // section, div, a, em, span: their words stay, the tag goes.
  }
  flush();
  return { title, effective, blocks };
}

const terms = parsePage(path.join(siteDir, "terms.html"));
const privacy = parsePage(path.join(siteDir, "privacy.html"));
const version = [isoDate(terms.effective), isoDate(privacy.effective)].sort().pop();

const out = `// GENERATED by scripts/gen-legal.js from libotbulacan.com's terms.html and
// privacy.html — do not edit by hand; change the website, then run the script.
// The sign-up consent pop-up (components/LegalConsentModal.js) shows these.

// What the backend records as the version a traveler agreed to (the later of
// the two pages' effective dates; utils/signUpDetails.js there).
export const LEGAL_VERSION = ${JSON.stringify(version)};

export const LEGAL_DOCS = ${JSON.stringify([terms, privacy], null, 2)};
`;
fs.writeFileSync(outFile, out);
console.log(`Wrote ${path.relative(process.cwd(), outFile)}: ${terms.blocks.length} + ${privacy.blocks.length} blocks, version ${version}.`);
